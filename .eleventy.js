const fs = require("fs");
const path = require("path");
const eleventyImage = require("@11ty/eleventy-img");
const generateImage = eleventyImage.default || eleventyImage;
const { generateHTML } = eleventyImage;
const CleanCSS = require("clean-css");
const { minify: minifyJs } = require("terser");
const { minify: minifyHtml } = require("html-minifier-terser");

const IS_PROD = process.env.ELEVENTY_RUN_MODE !== "serve";

module.exports = function (eleventyConfig) {
  eleventyConfig.addPassthroughCopy({ "src/admin": "admin" });
  eleventyConfig.addPassthroughCopy({ "src/assets/img": "assets/img" });
  eleventyConfig.addPassthroughCopy({ "src/assets/fonts": "assets/fonts" });
  eleventyConfig.addWatchTarget("./content.json");
  eleventyConfig.addWatchTarget("./src/assets/css/");
  eleventyConfig.addWatchTarget("./src/assets/js/");

  /* ======================================================================
     CSS — minified and inlined into every page.
     The whole stylesheet gzips to a few KB, so inlining it removes the only
     render-blocking request on the site. Nothing to split into "critical".
     ====================================================================== */
  let cssCache = null;
  eleventyConfig.addShortcode("inlineCss", function () {
    if (cssCache === null) {
      // fonts.css is generated by `npm run fonts` and only exists once the
      // display face has been self-hosted. Prepended so @font-face lands first.
      const faces = fs.existsSync("src/assets/css/fonts.css")
        ? fs.readFileSync("src/assets/css/fonts.css", "utf8")
        : "";
      const raw = faces + fs.readFileSync("src/assets/css/style.css", "utf8");
      cssCache = IS_PROD ? new CleanCSS({ level: 2 }).minify(raw).styles : raw;
    }
    return `<style>${cssCache}</style>`;
  });
  eleventyConfig.on("eleventy.before", () => { cssCache = null; });

  /* ======================================================================
     JS — minified, written to _site, loaded with defer.
     Kept external so it stays cached across pages.
     ====================================================================== */
  eleventyConfig.on("eleventy.after", async ({ dir }) => {
    // Every .js in src/assets/js, not just main.js. This used to name main.js
    // explicitly, so adding boot.js produced a <script src> pointing at a file
    // that was never emitted — a silent 404 that check.js also missed, because
    // it only validated href= and never src=. Both are fixed.
    const from = "src/assets/js";
    const target = path.join(dir.output, "assets", "js");
    fs.mkdirSync(target, { recursive: true });
    for (const name of fs.readdirSync(from)) {
      if (!name.endsWith(".js")) continue;
      const src = fs.readFileSync(path.join(from, name), "utf8");
      const out = IS_PROD ? (await minifyJs(src, { format: { comments: false } })).code : src;
      fs.writeFileSync(path.join(target, name), out);
    }
  });

  /* ======================================================================
     IMAGES — AVIF + WebP + original, multiple widths, srcset, lazy, sized.
     Drop a real .jpg into src/assets/img/, point content.json at it, and the
     whole pipeline runs automatically. SVG placeholders pass straight
     through untouched.
     ====================================================================== */
  const imageWidths = [480, 800, 1200, 1800, null];

  async function imageShortcode(src, alt, sizes, className, loading, fetchpriority) {
    if (alt === undefined || alt === null) {
      throw new Error(`Missing alt text on image: ${src}`);
    }
    const input = path.join("src", String(src).replace(/^\//, ""));
    if (!fs.existsSync(input)) {
      // Missing file: render something visible rather than failing the build.
      return `<img src="${src}" alt="${alt}"${className ? ` class="${className}"` : ""} loading="lazy" decoding="async">`;
    }

    const metadata = await generateImage(input, {
      widths: imageWidths,
      formats: ["avif", "webp", "auto"],
      svgShortCircuit: true,
      urlPath: "/assets/img/opt/",
      outputDir: "./_site/assets/img/opt/",
      sharpAvifOptions: { quality: 62 },
      sharpWebpOptions: { quality: 78 },
      sharpJpegOptions: { quality: 80, progressive: true, mozjpeg: true },
    });

    return generateHTML(metadata, {
      alt,
      sizes: sizes || "100vw",
      loading: loading || "lazy",
      decoding: "async",
      ...(className ? { class: className } : {}),
      ...(fetchpriority ? { fetchpriority } : {}),
    });
  }
  eleventyConfig.addAsyncShortcode("image", imageShortcode);

  /* ======================================================================
     FILTERS
     ====================================================================== */
  eleventyConfig.addFilter("absUrl", function (p, base) {
    const b = String(base || "").replace(/\/+$/, "");
    const s = String(p || "/");
    return b + (s.startsWith("/") ? s : "/" + s);
  });

  /** Safe JSON-LD: escapes the sequence that would close the script tag. */
  eleventyConfig.addFilter("jsonld", function (obj) {
    return JSON.stringify(obj, null, 0)
      .replace(/</g, "\\u003c")
      .replace(/>/g, "\\u003e")
      .replace(/&/g, "\\u0026");
  });

  eleventyConfig.addFilter("clamp", function (s, n) {
    const str = String(s || "");
    if (str.length <= n) return str;
    return str.slice(0, str.lastIndexOf(" ", n)) + "…";
  });

  /** Turn blank-line-separated copy into paragraphs. */
  eleventyConfig.addFilter("paras", function (s) {
    return String(s || "")
      .split(/\n{2,}|\r\n\r\n/)
      .map((p) => p.trim())
      .filter(Boolean)
      // A paragraph still holding [instructions] or a TPS_ token is not
      // finished copy, so it never reaches the page.
      .filter((p) => !/TPS_[A-Z_]+|\[[^\]]{3,}\]/.test(p));
  });

  eleventyConfig.addFilter("where", (arr, key, value) => (arr || []).filter((i) => i[key] === value));
  /* Areas map: a town's position on the /areas/ map, and its straight-line
     distance in miles from the base (contact.geo). The map is centred on the
     base at (300, 215) in a 600 x 480 viewBox, 26px to the mile. */
  eleventyConfig.addFilter("mapPoint", function (p, base) {
    if (!p || p.lat == null || !base) return null;
    const R = 3958.8, rad = (d) => (d * Math.PI) / 180;
    const dLat = rad(p.lat - base.latitude), dLng = rad(p.lng - base.longitude);
    const dx = dLng * Math.cos(rad(base.latitude)) * R, dy = dLat * R;
    const miles = Math.sqrt(dx * dx + dy * dy);
    return { x: Math.round((300 + dx * 26) * 10) / 10, y: Math.round((215 - dy * 26) * 10) / 10, miles: miles < 0.5 ? 0 : Math.round(miles) };
  });
  eleventyConfig.addFilter("limit", (arr, n) => (arr || []).slice(0, n));

  /* ======================================================================
     HTML minification
     ====================================================================== */
  eleventyConfig.addTransform("htmlmin", async function (content) {
    if (!IS_PROD || !(this.page.outputPath || "").endsWith(".html")) return content;
    return minifyHtml(content, {
      collapseWhitespace: true,
      conservativeCollapse: false,
      removeComments: true,
      minifyCSS: true,
      minifyJS: true,
      removeRedundantAttributes: true,
      useShortDoctype: true,
      sortAttributes: true,
      sortClassName: true,
    });
  });

  return {
    dir: { input: "src", output: "_site", includes: "_includes", data: "_includes" },
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk",
    pathPrefix: "/",
  };
};
